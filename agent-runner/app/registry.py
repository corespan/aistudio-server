# token and answers CORS itself, so the gateway only forwards (Authorization untouched) and streams.
# ponytail: no gateway jwtAuth here; the runner is the only check. Add jwtAuth + backendAuth
# passthrough if junk traffic ever needs stopping before the runner.
RUNNER_ROUTE = {"matches": [{"path": {"pathPrefix": "/assistant/"}}],
                "backends": [{"host": "agent-runner:8060"}],
                "policies": {"urlRewrite": {"path": {"prefix": "/"}}}}
SANDBOX_HEADER = """# GENERATED by `make registry` from agent-runner/platform/ (packs/*/models/*.yaml). Don't edit.
#
# agentgateway-sandbox: the only thing workspace sandboxes can reach (network sandbox-egress, no
# other route out). Its own container because agentgateway can't bind a listener to one network:
# on the main gateway, sandboxes could also reach /mcp/* and /llm. /llm/anthropic checks the
# Keycloak token and its user, then swaps it for your Claude subscription token, which only this
# container holds. /mcp/<name>: only the tools the claude-code agents name (packs/*/agents/*.yaml),
# for the same users, with the token passed on so the MCP server checks it again.
"""


class Invalid(ValueError):
    """Every problem found, one per line."""


@dataclass(frozen=True)
class Registry:
    hash: str
    agents: dict[str, Harness]
    connectors: dict[str, Connector]
    models: dict[str, Model]
    repos: list[str]
    workflows: dict[str, Workflow]


def _yaml(path: Path):
    return yaml.safe_load(path.read_text(encoding="utf-8"))


def _hash(body: dict) -> str:
    return hashlib.sha256(json.dumps(body, sort_keys=True).encode()).hexdigest()


def build(root: Path) -> dict:
    """The lock file's content, or Invalid naming every problem."""
    errors: list[str] = []
    try:
        platform = Platform.model_validate(_yaml(root / "platform.yaml"))
    except (OSError, yaml.YAMLError, ValidationError) as exc:
        raise Invalid(f"platform.yaml: {exc}") from exc
    body: dict = {"platform": platform.model_dump(), "packs": {}, **{k: {} for k in KINDS}}

    for name in platform.packs:
        folder = root / "packs" / name
        try:
            pack = Pack.model_validate(_yaml(folder / "pack.yaml"))
        except (OSError, yaml.YAMLError, ValidationError) as exc:
            errors.append(f"packs/{name}/pack.yaml: {exc}")
            continue
        if pack.name != name:
            errors.append(f"packs/{name}/pack.yaml: name is {pack.name!r}, not the folder's {name!r}")
        errors += [f"pack {name} requires pack {r!r}, which platform.yaml doesn't enable"
                   for r in pack.requires if r not in platform.packs]
        body["packs"][name] = pack.model_dump()
        for path in sorted(p for p in folder.rglob("*.yaml") if p.name != "pack.yaml"):
            rel = path.relative_to(root).as_posix()
            try:
                doc = _yaml(path) or {}
                kind = doc.get("kind")
                if kind not in KINDS:
                    errors.append(f"{rel}: kind {kind!r} is not one of {sorted(KINDS)}")
                    continue
                item = KINDS[kind].model_validate(doc)
            except (yaml.YAMLError, ValidationError, AttributeError) as exc:
                errors.append(f"{rel}: {exc}")
                continue
            if item.name in body[kind]:
                errors.append(f"{rel}: {kind} {item.name!r} is already in {body[kind][item.name]['source']}")
                continue
            body[kind][item.name] = {"source": rel, "spec": item.model_dump()}

    # Every agent tool names a connector this install has: connector/tool. A claude-code agent's
    # model is a model file.
    for name, entry in body["agent"].items():
        spec = entry["spec"]
        if spec["engine"] == "claude-code" and spec["model"] not in body["model"]:
            errors.append(f"{entry['source']}: model {spec['model']!r} is not a model file in an enabled pack")
        for pattern in entry["spec"]["tools"]:
            connector, _, tool = pattern.partition("/")
            if not tool:
                errors.append(f"{entry['source']}: tool {pattern!r} must be connector/tool")
            elif connector not in body["connector"]:
                errors.append(f"{entry['source']}: tool {pattern!r} names connector {connector!r}, "
                              f"which no enabled pack has")
    errors += [f"{e['source']}: {problem}" for e in body["workflow"].values()
               for problem in _workflow_problems(e["spec"], body)]
    if errors:
        raise Invalid("\n".join(errors))
    return {"hash": _hash(body), **body}


def _workflow_problems(wf: dict, body: dict) -> list[str]:
    """A workflow's steps name claude-code agents, look only backwards, and send work back only
    to an earlier step; its repo is one the sandbox gateway serves."""
    out = [] if wf["repo"] in body["platform"]["repos"] else [f"repo {wf['repo']!r} is not in platform.yaml's repos"]
    seen: list[str] = []
    gate_ok = False      # a write gate, with only learn steps after it
    for s in wf["steps"]:
        if s["gate"]:
            gate_ok = s["gate"] == "write"
        elif s["agent"] and s["mode"] != "learn" or s["run"]:
            gate_ok = False
        if s["publish"] and not gate_ok:
            out.append(f"step {s['id']}: publish comes only after a write gate, with only learn between")
        if s["publish"] and s["publish"] not in {"task": ("pr",), "pr": ("review", "push")}[wf["input"]]:
            out.append(f"step {s['id']}: a {wf['input']} workflow can't publish a {s['publish']}")
        agent = body["agent"].get(s["agent"] or "", {}).get("spec", {})
        if s["agent"] and agent.get("engine") != "claude-code":
            out.append(f"step {s['id']}: {s['agent']!r} is not a claude-code agent")
        out += [f"step {s['id']}: needs {n!r}, which is not an earlier step" for n in s["needs"] if n not in seen]
        if s["revise"] and s["revise"]["step"] not in seen:
            out.append(f"step {s['id']}: revise goes to {s['revise']['step']!r}, which is not an earlier step")
        if s["id"] in seen:
            out.append(f"step {s['id']}: the id is used twice")
        seen.append(s["id"])
    return out


def _text(body: dict) -> str:
    return json.dumps(body, indent=2, sort_keys=True) + "\n"


def _github(repos: list[str], users: list[str]) -> dict:
    """The runner's GitHub calls, the writes only after your approval: your PAT, added here.
    Only these REST calls on these repos. Read: a PR, its comments and its head's checks, a
    commit. Create: blobs, trees, commits, new refs, a PR, a review, review requests, a PR
    comment. Update: only refs under agent/ (pr-followup's push; the runner never forces).
    Nothing can be merged or deleted, and master can't be moved. Everything else is refused here."""
    names = "|".join(r.replace(".", "[.]") for r in repos)
    get = (f"^/github/repos/({names})/(pulls/[0-9]+|pulls/[0-9]+/comments|issues/[0-9]+/comments|"
           f"git/commits/[0-9a-f]{{40}}|commits/[0-9a-f]{{40}}/check-runs|check-runs/[0-9]+/annotations)$")
    post = (f"^/github/repos/({names})/(git/(blobs|trees|commits|refs)|pulls|pulls/[0-9]+/reviews|"
            f"pulls/[0-9]+/requested_reviewers|issues/[0-9]+/comments)$")
    patch = f"^/github/repos/({names})/git/refs/heads/agent/[A-Za-z0-9._/-]+$"
    rule = (f"{USER} in {users!r} && ((request.method == 'GET' && request.path.matches('{get}')) || "
            f"(request.method == 'POST' && request.path.matches('{post}')) || "
            f"(request.method == 'PATCH' && request.path.matches('{patch}') && !request.path.contains('..')))")
    return {"matches": [{"path": {"pathPrefix": "/github/"}}],
            "backends": [{"host": "api.github.com:443"}],
            "policies": {
                "jwtAuth": JWT,
                "authorization": {"rules": [rule]},
                "localRateLimit": [{"type": "requests", "maxTokens": 60, "tokensPerFill": 60, "fillInterval": "60s"}],
                "urlRewrite": {"authority": {"full": "api.github.com"}, "path": {"prefix": "/"}},
                "backendTLS": {},
                "requestHeaderModifier": {"set": {"authorization": "Bearer ${GITHUB_PAT}",
                                                  "user-agent": "aistudio-agent-runner",
                                                  "accept": "application/vnd.github+json",
                                                  "x-github-api-version": "2022-11-28"}}}}


def _audience(name: str, spec: dict) -> str:
    return spec.get("audience") or f"mcp:{name}"


def _route(name: str, spec: dict, outside: bool = False) -> dict:
    """/mcp/<name>. Inside (agent-runner): the Keycloak token checked, then passed through. Outside
    (MCP clients on the HTTPS port): MCP's own OAuth discovery, so clients find Keycloak's login."""
    backends = [{"mcp": {"targets": [{"name": name, "mcp": {"host": spec["upstream"]}}]}}]
    rules = {"backendAuth": {"passthrough": {}}, "mcpAuthorization": {"rules": spec["rules"]}}
    if not outside:
        return {"matches": [{"path": {"pathPrefix": f"/mcp/{name}"}}], "backends": backends,
                "policies": {"jwtAuth": JWT, **rules}}
    return {"matches": [{"path": {"pathPrefix": f"/mcp/{name}"}},
                        {"path": {"exact": f"/.well-known/oauth-protected-resource/mcp/{name}"}}],
            "backends": backends,
            "policies": {
                # Browser clients on any origin (no cookies: a page needs the token itself). The server's
                # own Origin check (DNS rebinding) knows only its compose name, so the gateway drops Origin.
                "cors": {"allowOrigins": ["*"], "allowMethods": ["GET", "POST", "DELETE", "OPTIONS"],
                         "allowHeaders": ["authorization", "content-type", "accept", "mcp-session-id",
                                          "mcp-protocol-version", "last-event-id"],
                         "exposeHeaders": ["mcp-session-id", "www-authenticate"], "maxAge": "600s"},
                "requestHeaderModifier": {"remove": ["origin"]},
                # Keycloak is the authorization server clients are sent to, so its issuer is the one
                # they check (RFC 9207); no gateway adapter in between.
                "mcpAuthentication": {"mode": "strict", "issuer": ISSUER, "audiences": [_audience(name, spec)],
                                      "jwks": JWKS,
                                      "resourceMetadata": {"resource": f"${{MCP_PUBLIC_URL}}/mcp/{name}",
                                                           "scopesSupported": ["openid"],
                                                           "bearerMethodsSupported": ["header"]}},
                **rules}}


def _anthropic(users: list[str]) -> dict:
    """Claude Code in a sandbox -> Anthropic, on your subscription (docs/agent-runner.md#the-anthropic-route)."""
    return {"matches": [{"path": {"pathPrefix": "/llm/anthropic"}}],
            "backends": [{"host": "api.anthropic.com:443"}],
            "policies": {
                "jwtAuth": JWT,
                "authorization": {"rules": [f"{USER} in {users!r}"]},
                # Backstop for a runaway loop even if the runner's limits have a bug. Claude Code retries 429s.
                "localRateLimit": [{"type": "requests", "maxTokens": 60, "tokensPerFill": 60, "fillInterval": "60s"}],
                "urlRewrite": {"authority": {"full": "api.anthropic.com"}, "path": {"prefix": "/"}},
                "backendTLS": {},
                "requestHeaderModifier": {"set": {"authorization": "Bearer ${CLAUDE_CODE_OAUTH_TOKEN}"},
                                          "add": {"anthropic-beta": "oauth-2025-04-20"}, "remove": ["x-api-key"]}}}


def _sandbox_mcp(name: str, spec: dict, tools: list[str], users: list[str]) -> dict:
    """/mcp/<name> for Claude Code in a sandbox: only the tools some claude-code agent names, only
    for the subscription's users, and still the connector's role rules. Anything else running in a
    workspace (a repo's tests, say) gets no more than that."""
    route = _route(name, spec)
    only = f"{USER} in {users!r} && mcp.tool.name in {sorted(tools)!r}"
    route["policies"]["mcpAuthorization"] = {"rules": [f"({rule}) && {only}" for rule in spec["rules"]]}
    return route


def _git(repo: str) -> list[dict]:
    """Clone and fetch only: the two smart-HTTP read endpoints, matched exactly. Push
    (git-receive-pack) and everything else has no route. The JWT is dropped: GitHub gets nothing."""
    policies = {"jwtAuth": JWT, "backendTLS": {},
                "requestHeaderModifier": {"remove": ["authorization"]}}
    out = []
    for method, path, query in (("GET", "info/refs", [{"name": "service", "value": {"exact": "git-upload-pack"}}]),
                                ("POST", "git-upload-pack", [])):
        match = {"path": {"exact": f"/git/{repo}.git/{path}"}, "method": method} | ({"query": query} if query else {})
        out.append({"matches": [match], "backends": [{"host": "github.com:443"}],
                    "policies": {**policies, "urlRewrite": {"authority": {"full": "github.com"},
                                                            "path": {"full": f"/{repo}.git/{path}"}}}})
    return out


def render(body: dict) -> dict[Path, str]:
    """Every file the registry writes, by path."""
    root = Path(settings.platform_dir)
    connectors = {n: e["spec"] for n, e in sorted(body["connector"].items())}
    # ponytail: one model behind /llm for every logical name; the model kind (step 3) adds a route each.
    llm = {"matches": [{"path": {"pathPrefix": "/llm"}}],
           "backends": [{"ai": {"name": "llm", "hostOverride": "${LLM_HOST}", "pathOverride": "/v1/chat/completions",
                                "provider": {"openAI": {"model": "${LLM_MODEL}"}}}}],
           "policies": {"jwtAuth": JWT, "backendAuth": {"key": "${LLM_API_KEY}"}}}
    inside = [llm] + [_route(n, s) for n, s in connectors.items()]
    publishing = [e["spec"] for e in body["workflow"].values()
                  if any(s["publish"] for s in e["spec"]["steps"]) or e["spec"]["input"] == "pr"]
    if publishing:
        inside.append(_github(sorted({w["repo"] for w in publishing}),
                              sorted({u for w in publishing for u in w["users"]})))
    outside = ([_route(n, s, outside=True) for n, s in connectors.items() if s["browser"]]
               + KEYCLOAK_ROUTES + [RUNNER_ROUTE])
    gateway = {"config": {"adminAddr": "127.0.0.1:15000"}, "binds": [
        # HTTPS only; mint.py tls issues the cert from the local CA (make mcp-init / mcp-up).
        {"port": 8050, "listeners": [{"protocol": "HTTPS", "tls": TLS, "routes": outside}]},
        {"port": 8052, "listeners": [{"routes": inside}]}]}
    # Every token carries all of these (kc.py setup adds a mapper for each), so each service can check
    # its own: the gateway, the runner, and each connector's server.
    audiences = list(dict.fromkeys([GATEWAY_AUDIENCE, settings.jwt_audience]
                                   + [_audience(n, s) for n, s in connectors.items()]))
    out = root.parent.parent / "gateway"
    files = {root / LOCK: _text(body),
             out / "config.yaml": HEADER + yaml.safe_dump(gateway, sort_keys=False, width=10_000),
             out / "audiences.json": json.dumps(audiences, indent=2) + "\n"}
    users = sorted({u for e in body["model"].values() if e["spec"]["provider"] == "anthropic"
                    for u in e["spec"]["users"]})
    if users:
        wanted: dict[str, set[str]] = {}       # connector -> the tools claude-code agents name on it
        for e in body["agent"].values():
            if e["spec"]["engine"] == "claude-code":
                for pattern in e["spec"]["tools"]:
                    connector, _, tool = pattern.partition("/")
                    wanted.setdefault(connector, set()).add(tool)
        mcp_routes = [_sandbox_mcp(n, connectors[n], sorted(t), users) for n, t in sorted(wanted.items())]
        sandbox = {"config": {"adminAddr": "127.0.0.1:15000"},
                   "binds": [{"port": 8051, "listeners": [{"routes": [_anthropic(users)] + mcp_routes + [
                       r for repo in body["platform"]["repos"] for r in _git(repo)]}]}]}
        files[out / "sandbox.yaml"] = SANDBOX_HEADER + yaml.safe_dump(sandbox, sort_keys=False, width=10_000)
    return files


@lru_cache(maxsize=1)
def load() -> Registry:
    """The lock file this process runs with."""
    body = json.loads((Path(settings.platform_dir) / LOCK).read_text(encoding="utf-8"))
    digest = body.pop("hash")
    if _hash(body) != digest:
        raise Invalid(f"{LOCK} was edited by hand; run `make registry`")
    return Registry(
        hash=digest,
        agents={n: Harness.model_validate(e["spec"]) for n, e in body["agent"].items()},
        connectors={n: Connector.model_validate(e["spec"]) for n, e in body["connector"].items()},
        models={n: Model.model_validate(e["spec"]) for n, e in body["model"].items()},
        repos=body["platform"]["repos"],
        workflows={n: Workflow.model_validate(e["spec"]) for n, e in body["workflow"].items()})


def main(argv: list[str]) -> int:
    if argv[1:] not in (["render"], ["check"]):
        print(__doc__)
        return 2
    try:
        files = render(build(Path(settings.platform_dir)))
    except Invalid as exc:
        print(exc, file=sys.stderr)
        return 1
    stale = [p for p, text in files.items() if not p.exists() or p.read_text(encoding="utf-8") != text]
    if argv[1] == "render":
        for path in stale:
            path.write_text(files[path], encoding="utf-8", newline="\n")
            print(f"wrote {path}")
        return 0
    for path in stale:
        print(f"{path} is out of date: run `make registry`", file=sys.stderr)
    if not stale:
        print("registry.lock.json and the gateway files are up to date")
    return 1 if stale else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
